"""dd100 command line.

    dd100 validate                      check the framework (100 dims, weights, gates)
    dd100 list [--pillar K]             print the dimensions
    dd100 metrics                       every metric the rules and gates read
    dd100 template <project_dir>        write a blank assessment sheet for agent/human dims
    dd100 collect <manifest>            fetch public data into evidence/auto.json
    dd100 run <manifest> [--llm] [--out DIR]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

from . import __version__
from .framework import FrameworkError, load_framework


def cmd_validate(_: argparse.Namespace) -> int:
    fw = load_framework()
    methods = {}
    for d in fw.dimensions.values():
        methods[d.method] = methods.get(d.method, 0) + 1
    print(f"✓ framework OK — {len(fw.dimensions)} dimensions in {len(fw.pillars)} pillars")
    print("  methods: " + ", ".join(f"{k}={v}" for k, v in sorted(methods.items())))
    print(f"  gates:   {len(fw.gates)} ("
          + ", ".join(f"{s}={sum(1 for g in fw.gates if g['severity'] == s)}" for s in ("critical", "major", "minor"))
          + ")")
    print("  profiles: " + ", ".join(fw.config["profiles"]))
    return 0


def cmd_list(args: argparse.Namespace) -> int:
    fw = load_framework()
    if args.md:
        print("# The 100 dimensions\n\nGenerated by `dd100 list --md` from `framework/dimensions.yaml`.\n")
        print("Method: **rule** = computed from a metric · **agent** = cited judgment · **human** = private channel only.\n")
        for p, name in fw.pillars.items():
            print(f"## {p} · {name}\n\n| ID | Dimension | Method | W | Question / scoring |\n|---|---|---|---:|---|")
            for d in fw.by_pillar(p):
                if d.rule and d.rule["direction"] == "bool":
                    how = f"`{d.rule['metric']}` must be `{str(d.rule['pass']).lower()}`"
                elif d.rule:
                    sym = "≥" if d.rule["direction"] == "higher" else "≤"
                    how = f"`{d.rule['metric']}` " + " / ".join(f"{sc}:{sym}{t:,g}" for sc, t in zip((4, 3, 2, 1), d.rule["bands"]))
                else:
                    how = f"0 = {d.anchors[0]}; 4 = {d.anchors[4]}"
                print(f"| {d.id} | {d.name} | {d.method} | {d.weight} | {d.question}<br>{how} |")
            print()
        return 0
    for p, name in fw.pillars.items():
        if args.pillar and p != args.pillar.upper():
            continue
        print(f"\n{p} · {name}")
        for d in fw.by_pillar(p):
            print(f"  {d.id}  [{d.method:<5}] w{d.weight}  {d.name}")
    return 0


def cmd_metrics(_: argparse.Namespace) -> int:
    """Every metric name the framework reads, generated from the YAML so it never drifts."""
    fw = load_framework()
    used: dict[str, list[str]] = {}
    for d in fw.dimensions.values():
        if d.rule:
            used.setdefault(d.rule["metric"], []).append(f"{d.id} {d.name}")
    for g in fw.gates:
        for c in g["when"]["all"]:
            if "metric" in c:
                used.setdefault(c["metric"], []).append(f"{g['id']} gate ({g['severity']})")
    derived = {"contradiction_count", "fdv_to_mcap", "volume_to_depth_ratio",
               "fdv_to_annual_fees", "circulating_supply_pct"}
    print("| Metric | Used by | Supplied by |\n|---|---|---|")
    for name in sorted(used):
        who = "harness (derived)" if name in derived else "evidence pack"
        print(f"| `{name}` | {'; '.join(used[name])} | {who} |")
    print("\nDerived metrics need their inputs: `fdv_usd`, `market_cap_usd`, `volume_24h_usd`, "
          "`depth_2pct_usd`, `annualized_fees_usd`, `circulating_supply`, `total_supply`.")
    return 0


def cmd_template(args: argparse.Namespace) -> int:
    fw = load_framework()
    out = Path(args.project_dir) / "assessments" / "template.yaml"
    out.parent.mkdir(parents=True, exist_ok=True)
    lines = ["# Fill in score (0-4), confidence, evidence ids and a one-line rationale.",
             "# Leave `status: pending` where evidence is missing — never guess.", "assessments:"]
    for d in fw.dimensions.values():
        if d.method == "rule":
            continue
        lines += [f"  # {d.id} {d.name} — {d.question}",
                  *[f"  #   {k}: {v}" for k, v in sorted(d.anchors.items())],
                  f"  - id: {d.id}", "    status: pending",
                  f"    assessor: \"{'human:analyst' if d.method == 'human' else 'agent:claude'}\"",
                  "    score:", "    confidence:", "    evidence: []", "    rationale: \"\"", ""]
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out}")
    return 0


def cmd_collect(args: argparse.Namespace) -> int:
    from .collectors import collect_all
    manifest = Path(args.manifest)
    m = yaml.safe_load(manifest.read_text(encoding="utf-8"))
    cfg = m.get("collect") or {}
    if not cfg:
        print("manifest has no `collect:` block — nothing to fetch", file=sys.stderr)
        return 1
    part, errors = collect_all(cfg)
    part.update({"project": m["project"], "as_of": str(m.get("as_of", "")), "claims": []})
    out = manifest.parent / "evidence" / "auto.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(part, indent=2), encoding="utf-8")
    print(f"wrote {out} — {len(part['metrics'])} metrics from {len(part['sources'])} sources")
    for e in errors:
        print(f"  ✖ {e}", file=sys.stderr)
    print("Add 'evidence/auto.json' to the manifest's evidence list to use it.")
    return 1 if errors and not part["metrics"] else 0


def cmd_run(args: argparse.Namespace) -> int:
    from .harness import run
    from .report import VERDICT_BADGE, write_outputs
    manifest = Path(args.manifest)
    fw = load_framework()
    a, pack = run(manifest, use_llm=args.llm, fw=fw)
    out = Path(args.out) if args.out else manifest.parent / "report"
    write_outputs(a, fw, pack, out)

    score = "—" if a.point_score is None else f"{a.point_score:.1f}"
    counts = {}
    for s in a.dims.values():
        counts[s.status] = counts.get(s.status, 0) + 1
    print(f"\n{a.project}  ·  {VERDICT_BADGE[a.verdict]}  ·  grade {a.grade}  ·  {score}/100 "
          f"(range {a.score_low:.0f}–{a.score_high:.0f})  ·  coverage {a.coverage:.0%}")
    print("  dimensions: " + ", ".join(f"{k}={v}" for k, v in sorted(counts.items())))
    for g in a.gates:
        if g.status in ("fired", "unchecked"):
            print(f"  {'🚩' if g.status == 'fired' else '❔'} {g.id} [{g.severity}] {g.title} — {g.status}")
    for r in a.verdict_reasons:
        print(f"  → {r}")
    print(f"  reports: {out}/report.md, memo.md, radar.svg, scorecard.json")
    return 0


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="dd100", description="100-dimension crypto due-diligence harness")
    ap.add_argument("--version", action="version", version=f"dd100 {__version__}")
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("validate").set_defaults(fn=cmd_validate)
    p = sub.add_parser("list"); p.add_argument("--pillar"); p.add_argument("--md", action="store_true")
    p.set_defaults(fn=cmd_list)
    sub.add_parser("metrics").set_defaults(fn=cmd_metrics)
    p = sub.add_parser("template"); p.add_argument("project_dir"); p.set_defaults(fn=cmd_template)
    p = sub.add_parser("collect"); p.add_argument("manifest"); p.set_defaults(fn=cmd_collect)
    p = sub.add_parser("run"); p.add_argument("manifest"); p.add_argument("--llm", action="store_true")
    p.add_argument("--out"); p.set_defaults(fn=cmd_run)
    args = ap.parse_args(argv)
    try:
        return args.fn(args)
    except FrameworkError as e:
        print(f"✖ framework error: {e}", file=sys.stderr)
        return 2
    except (ValueError, RuntimeError, FileNotFoundError) as e:
        print(f"✖ {type(e).__name__}: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
